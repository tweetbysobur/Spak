export const WALLET_FAMILIES = ["evm", "solana", "near"] as const;
export type WalletFamily = (typeof WALLET_FAMILIES)[number];
export type ChallengePurpose = "SIGN_IN" | "LINK";

export const AUTH_ERROR_CODES = [
  "UNAUTHENTICATED", "SESSION_EXPIRED", "FORBIDDEN", "BAD_REQUEST", "INVALID_ADDRESS", "CHALLENGE_NOT_FOUND",
  "CHALLENGE_EXPIRED", "CHALLENGE_USED", "SIGNATURE_INVALID", "KEY_NOT_AUTHORIZED", "WALLET_OWNED_BY_OTHER_USER",
  "WALLET_ALREADY_LINKED", "WALLET_NOT_FOUND", "LAST_WALLET", "NETWORK_NOT_SUPPORTED", "RATE_LIMITED", "RATE_LIMIT_UNAVAILABLE", "CSRF",
  "NEAR_RPC_UNAVAILABLE", "AGENT_ALREADY_LINKED",
] as const;
export type AuthErrorCode = (typeof AUTH_ERROR_CODES)[number];

const STATUS: Record<AuthErrorCode, number> = {
  UNAUTHENTICATED: 401, SESSION_EXPIRED: 401, FORBIDDEN: 403, BAD_REQUEST: 400, INVALID_ADDRESS: 400,
  CHALLENGE_NOT_FOUND: 400, CHALLENGE_EXPIRED: 400, CHALLENGE_USED: 409, SIGNATURE_INVALID: 401, KEY_NOT_AUTHORIZED: 401,
  WALLET_OWNED_BY_OTHER_USER: 409, WALLET_ALREADY_LINKED: 409, WALLET_NOT_FOUND: 404, LAST_WALLET: 409,
  NETWORK_NOT_SUPPORTED: 400, RATE_LIMITED: 429, RATE_LIMIT_UNAVAILABLE: 503, CSRF: 403, NEAR_RPC_UNAVAILABLE: 503, AGENT_ALREADY_LINKED: 409,
};

export class AuthError extends Error {
  readonly status: number;
  constructor(public readonly code: AuthErrorCode, message: string) {
    super(message);
    this.name = "AuthError";
    this.status = STATUS[code];
  }
}
