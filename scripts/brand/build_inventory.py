"""
Brand asset inventory. Writes public/brand/manifest.json (machine-readable, with SHA-256) and docs/SPAK-BRAND-ASSETS.md.
Run after any approved asset change: python3 scripts/brand/build_inventory.py
"""
import hashlib, json, os, re
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BRAND = os.path.join(ROOT, 'public/brand')
PURPOSE = {
 'references/spak-symbol-reference.png': ('reference', 'Approved symbol direction (original upload, uncompressed). Never used in products'),
 'logo/spak-logo-horizontal.svg': ('logo', 'Primary logo, light surfaces'),
 'logo/spak-logo-horizontal-dark.svg': ('logo', 'Primary logo, dark surfaces (Muted Sage symbol, Warm White wordmark)'),
 'logo/spak-logo-horizontal-mono-graphite.svg': ('logo', 'Single colour Graphite'),
 'logo/spak-logo-horizontal-mono-black.svg': ('logo', 'Single colour black (print, engraving)'),
 'logo/spak-logo-horizontal-mono-white.svg': ('logo', 'Single colour Warm White (Forest Green, Graphite, photos)'),
 'logo/spak-logo-stacked.svg': ('logo', 'Stacked lockup, light surfaces'),
 'logo/spak-logo-stacked-dark.svg': ('logo', 'Stacked lockup, dark surfaces'),
 'logo/spak-symbol.svg': ('symbol', 'Master symbol, Forest Green'),
 'logo/spak-symbol-dark.svg': ('symbol', 'Symbol, Muted Sage for Graphite surfaces'),
 'logo/spak-symbol-white.svg': ('symbol', 'Symbol, Warm White for Forest Green surfaces'),
 'logo/spak-symbol-mono-graphite.svg': ('symbol', 'Symbol, Graphite'),
 'logo/spak-symbol-mono-black.svg': ('symbol', 'Symbol, black'),
 'logo/spak-symbol-small.svg': ('symbol', 'Optical-size symbol without the leaf, 16-24 px only'),
 'logo/spak-wordmark.svg': ('wordmark', 'Wordmark, Graphite'),
 'logo/spak-wordmark-green.svg': ('wordmark', 'Wordmark, Forest Green'),
 'logo/spak-wordmark-dark.svg': ('wordmark', 'Wordmark, Warm White'),
 'logo/spak-wordmark-mono-black.svg': ('wordmark', 'Wordmark, black'),
 'icons/spak-app-icon.svg': ('icon', 'App icon, rounded tile'),
 'icons/spak-app-icon-square.svg': ('icon', 'App icon, full-bleed square (platform masks)'),
 'icons/spak-app-icon-512.png': ('icon', 'App icon raster 512'),
 'icons/spak-app-icon-1024.png': ('icon', 'App icon raster 1024 (store listings)'),
 'icons/favicon.svg': ('icon', 'Favicon, small-size symbol'),
 'icons/favicon-full.svg': ('icon', 'Favicon with leaf, 32 px and up'),
 'icons/favicon.ico': ('icon', 'Favicon 16/32/48'),
 'icons/apple-touch-icon.png': ('icon', 'Apple touch icon 180'),
 'icons/icon-192.png': ('icon', 'Web app manifest 192'),
 'icons/icon-512.png': ('icon', 'Web app manifest 512'),
 'previews/spak-logo-horizontal-1200.png': ('preview', 'Preview only'),
 'previews/spak-logo-horizontal-dark-1200.png': ('preview', 'Preview only'),
 'previews/spak-logo-stacked-800.png': ('preview', 'Preview only'),
 'previews/spak-symbol-1024.png': ('preview', 'Preview only'),
 'previews/spak-brand-board.png': ('preview', 'Brand reference board render (2x)'),
 'images/spak-hero-landscape.png': ('image', 'Homepage hero background: misty mountain landscape, supplied and approved by the brand owner (original upload, uncompressed)'),
 'images/spak-hero-landscape-mobile.jpg': ('image', 'Homepage hero background for phones: portrait composition built from the landscape by scripts/brand/build_hero_mobile.py'),
 'images/spak-footer-landscape.jpg': ('image', 'Footer background: rolling hills and a winding path under a quiet sky (generated, approved by the brand owner)'),
 'board/spak-brand-board.html': ('board', 'Brand reference board (generated by scripts/brand/build_board.py)'),
}
items = []
for dirpath, _, files in os.walk(BRAND):
    for f in sorted(files):
        full = os.path.join(dirpath, f); rel = os.path.relpath(full, BRAND)
        if rel == 'manifest.json': continue
        if rel not in PURPOSE: raise SystemExit(f'unlisted brand file: {rel} (add it to PURPOSE)')
        data = open(full, 'rb').read(); kind, purpose = PURPOSE[rel]
        dims = None
        if f.endswith('.svg'):
            m = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', data.decode()); dims = f'{m.group(1)} x {m.group(2)} (viewBox)'
        elif f.endswith(('.png', '.ico', '.jpg')):
            im = Image.open(full); dims = ', '.join(f'{w}x{h}' for w, h in sorted(im.info['sizes'])) if f.endswith('.ico') else f'{im.width}x{im.height}'
        items.append({'path': f'public/brand/{rel}', 'kind': kind, 'format': f.rsplit('.', 1)[1], 'dimensions': dims, 'bytes': len(data),
                      'sha256': hashlib.sha256(data).hexdigest(), 'purpose': purpose, 'approved': kind not in ('preview', 'board')})
missing = [k for k in PURPOSE if not any(i['path'] == f'public/brand/{k}' for i in items)]
if missing: raise SystemExit(f'listed but missing: {missing}')
items.sort(key=lambda i: (['reference', 'logo', 'symbol', 'wordmark', 'icon', 'image', 'board', 'preview'].index(i['kind']), i['path']))
json.dump({'version': '1.0.0', 'generatedBy': 'scripts/brand/build_inventory.py', 'assets': items}, open(os.path.join(BRAND, 'manifest.json'), 'w'), indent=2)
open(os.path.join(BRAND, 'manifest.json'), 'a').write('\n')
L = ['# SPak Brand Asset Inventory', '', 'Generated by `scripts/brand/build_inventory.py`. The machine-readable version is `public/brand/manifest.json`, with SHA-256 checksums.',
     'The tests (`tests/brand/guidelines.test.ts`) fail if a brand file is added, removed or changed without regenerating the inventory.', '',
     '| File | Kind | Format | Dimensions | Size | Purpose |', '|---|---|---|---|---|---|']
for i in items: L.append(f"| `{i['path']}` | {i['kind']} | {i['format']} | {i['dimensions']} | {i['bytes']/1024:.1f} KB | {i['purpose']} |")
L += ['', '## Source and generator files', '', '| File | Purpose |', '|---|---|',
      '| `scripts/brand/symbol-geometry.json` | Vector geometry of the symbol (source of every logo SVG) |',
      '| `scripts/brand/lockup-metrics.json` | Lockup proportions: cap height, gap, tracking, kerning |',
      '| `scripts/brand/build_logo.py` | Regenerates all logo and icon SVGs |',
      '| `scripts/brand/build_colors.py` | Regenerates `src/design/colors.json` |',
      '| `scripts/brand/build_typography.py` | Regenerates `src/design/typography.json` and validates it against the font files |',
      '| `scripts/brand/build_board.py` | Regenerates the brand reference board |',
      '| `scripts/brand/build_hero_mobile.py` | Regenerates the portrait hero background for phones from the landscape |',
      '| `scripts/brand/build_inventory.py` | Regenerates this inventory and `public/brand/manifest.json` |',
      '| `src/design/colors.json` | Colour tokens |', '| `src/design/typography.json` | Typography tokens |', '| `src/design/fonts.ts` | Font loading (next/font) |', '',
      f'Totals: {len(items)} files, {sum(i["bytes"] for i in items)/1024:.0f} KB, of which {sum(1 for i in items if i["approved"])} are approved production assets.']
open(os.path.join(ROOT, 'docs/SPAK-BRAND-ASSETS.md'), 'w').write('\n'.join(L) + '\n')
print(len(items), 'assets')
