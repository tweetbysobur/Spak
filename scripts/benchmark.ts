import { writeFileSync } from "node:fs";
import { runBenchmark } from "../tests/benchmark/run-benchmark";
import { DATASET } from "../tests/benchmark/dataset";
import { HOLDOUT } from "../tests/benchmark/holdout";

type Summary = Awaited<ReturnType<typeof runBenchmark>>;

function table(s: Omit<Summary, "failures">) {
  return Object.entries(s).map(([k, v]) => `| ${k} | ${typeof v === "object" ? JSON.stringify(v) : v} |`).join("\n");
}
function failList(s: Summary) {
  return s.failures.map((f) => `- ${f.id} \`${f.text}\`: ${[f.type, f.status, ...f.fields, f.missing, f.code].filter(Boolean).join("; ")}`).join("\n") || "None.";
}

(async () => {
  const main = await runBenchmark(DATASET);
  const hold = await runBenchmark(HOLDOUT);
  for (const [name, s] of [["main", main], ["holdout", hold]] as const) {
    const { failures, ...metrics } = s;
    console.log(`== ${name} ==`);
    console.log(JSON.stringify(metrics, null, 2));
    for (const f of failures) console.log("FAIL", JSON.stringify(f));
  }
  if (process.argv.includes("--write")) {
    const { failures: _a, ...m } = main;
    const { failures: _b, ...h } = hold;
    writeFileSync("docs/BENCHMARK.md", [
      "# SPak-in benchmark", "",
      "Generated by `npm run bench -- --write`. Latency is local engine time per instruction, no network calls.", "",
      "## Main set", "", `${DATASET.length} labelled instructions in \`tests/benchmark/dataset.ts\`. The engine was tuned against this set, so treat it as a regression suite, not an accuracy estimate.`, "",
      "| Metric | Value |", "|---|---|", table(m), "",
      "First run of the main set, before any tuning (2026-11-10): classification 97.7%, entity extraction 96.7%, status 90.9%, ambiguity detection 97.7%, unsafe validations 0. After that run one label was corrected because the registry showed the expected answer was impossible (NEAR Intents lists no SOL on NEAR), and the comparison now accepts the documented NEAR = wNEAR equivalence.", "",
      "### Failures", "", failList(main), "",
      "## Held-out set", "", `${HOLDOUT.length} instructions in \`tests/benchmark/holdout.ts\`, written after tuning and not used to tune. This is the better estimate for unseen phrasing.`, "",
      "| Metric | Value |", "|---|---|", table(h), "", "### Failures", "", failList(hold), "",
    ].join("\n"));
  }
})();
